"""
Tidy the local scripts folder after Get Scripts, using the repo's retired.json.

Get Scripts only adds and updates files.  When a script is moved (e.g. Beta -> Release) or
renamed, the old copy would stay on the customer's PC and show up twice.  gamepro-scripts
publishes retired.json (generated by gamepro-app/tools/scripts_repo/make_retired.py):

    {
      "version": 1,
      "retired":    {"Beta/gen_3_frlg/FRLG_Shiny_Mewtwo.py": ["<sha256>", ...], ...},
      "moved_data": [{"from": "Beta/gen_3_frlg/pickup_items",
                      "to":   "Release/gen_3_frlg/pickup_items"}]
    }

- retired: paths that are no longer published, with the sha256 of every version that ever was.
  A local file is deleted only if it is byte-for-byte one of those versions, so a customer's own
  edits (or a file we never published) are never touched.
- moved_data: folders holding the user's own data next to a script (learned templates,
  screenshots...).  Files there are moved to the new folder unless one of that name already
  exists; published copies (matching a retired hash) are just deleted.
"""

import hashlib
import os
import shutil


def _sha256(path):
    h = hashlib.sha256()
    with open(path, 'rb') as f:
        for chunk in iter(lambda: f.read(65536), b''):
            h.update(chunk)
    return h.hexdigest()


def _inside(base, rel):
    """Absolute path for repo-relative `rel`, or None if it would leave `base`."""
    base = os.path.abspath(base)
    p = os.path.abspath(os.path.join(base, rel.replace('/', os.sep)))
    return p if os.path.commonpath([base, p]) == base and p != base else None


def _is_published(path, rel, retired):
    hashes = retired.get(rel)
    return bool(hashes) and _sha256(path) in hashes


def _remove_empty_dirs(base, start):
    """Remove `start` and its parents while they hold nothing but __init__.py / __pycache__."""
    base = os.path.abspath(base)
    d = os.path.abspath(start)
    while d != base and os.path.commonpath([base, d]) == base and os.path.isdir(d):
        names = [n for n in os.listdir(d) if n not in ('__init__.py', '__pycache__')]
        if names:
            break
        init = os.path.join(d, '__init__.py')
        if os.path.exists(init) and os.path.getsize(init) > 0:
            break                                    # someone's code - leave it
        shutil.rmtree(d, ignore_errors=True)
        d = os.path.dirname(d)


def apply_retired(manifest, scripts_dir):
    """Apply a parsed retired.json to scripts_dir.  Returns (removed, moved, kept) counts."""
    retired = manifest.get('retired') or {}
    removed = moved = kept = 0
    touched_dirs = set()

    for m in manifest.get('moved_data') or []:
        src, dst = _inside(scripts_dir, m.get('from', '')), _inside(scripts_dir, m.get('to', ''))
        if not src or not dst or not os.path.isdir(src):
            continue
        for root, dirs, files in os.walk(src):
            dirs[:] = [d for d in dirs if d != '__pycache__']
            for fn in files:
                p = os.path.join(root, fn)
                rel = os.path.relpath(p, scripts_dir).replace(os.sep, '/')
                if _is_published(p, rel, retired):
                    os.remove(p)                     # the new folder has the published copy
                    removed += 1
                    continue
                target = os.path.join(dst, os.path.relpath(p, src))
                if os.path.exists(target):
                    kept += 1                        # never overwrite at the destination
                    continue
                os.makedirs(os.path.dirname(target), exist_ok=True)
                shutil.move(p, target)
                moved += 1
        touched_dirs.add(src)

    for rel, hashes in retired.items():
        p = _inside(scripts_dir, rel)
        if not p or not os.path.isfile(p):
            continue
        if _sha256(p) in hashes:
            os.remove(p)
            removed += 1
            touched_dirs.add(os.path.dirname(p))
            if p.endswith('.py'):                    # its compiled copy, if any
                cache = os.path.join(os.path.dirname(p), '__pycache__')
                stem = os.path.splitext(os.path.basename(p))[0] + '.'
                if os.path.isdir(cache):
                    for c in os.listdir(cache):
                        if c.startswith(stem):
                            try:
                                os.remove(os.path.join(cache, c))
                            except OSError:
                                pass
        else:
            kept += 1                                # edited by the user - leave it

    for d in sorted(touched_dirs, key=len, reverse=True):
        _remove_empty_dirs(scripts_dir, d)
    return removed, moved, kept
