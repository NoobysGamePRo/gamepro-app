"""
Regenerate gamepro-scripts/retired.json from that repo's git history.

Every file Get Scripts copies (.py .md .png .jpg .jpeg .gif) that was ever committed but is not
in the current index is "retired", listed with the sha256 of every version that was committed.
The app (core/script_sync.py) deletes a customer's local copy only if it matches one of those.

Run it AFTER staging a move/rename (git mv ...), so the index already has the new layout:

    python tools/scripts_repo/make_retired.py [path/to/gamepro-scripts]

"moved_data" entries already in retired.json are kept.  Add one by hand for a folder of user
data that moves with a script (e.g. learned templates), then re-run.
"""

import hashlib
import json
import os
import subprocess
import sys

TYPES = ('.py', '.md', '.png', '.jpg', '.jpeg', '.gif')     # = SCRIPT_FILE_TYPES in gui/app.py


def git(repo, *args, binary=False):
    r = subprocess.run(['git', '-C', repo, *args], capture_output=True, check=True)
    return r.stdout if binary else r.stdout.decode('utf-8', 'replace')


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
        os.path.dirname(os.path.dirname(os.path.dirname(here))), 'gamepro-scripts')
    out = os.path.join(repo, 'retired.json')

    current = set(git(repo, 'ls-files', '-z').split('\0')) - {''}
    ever = set()
    for line in git(repo, 'log', '--all', '--format=', '--name-only', '-z').split('\0'):
        for p in line.split('\n'):
            p = p.strip()
            if p:
                ever.add(p)
    gone = sorted(p for p in ever - current
                  if p.lower().endswith(TYPES) and '__pycache__' not in p)

    retired = {}
    for p in gone:
        hashes = set()
        for blob in set(git(repo, 'log', '--all', '--format=%H', '--', p).split()):
            try:
                data = git(repo, 'show', f'{blob}:{p}', binary=True)
            except subprocess.CalledProcessError:
                continue                       # the commit that deleted it
            hashes.add(hashlib.sha256(data).hexdigest())
        if hashes:
            retired[p] = sorted(hashes)

    moved_data = []
    if os.path.exists(out):
        with open(out, encoding='utf-8') as f:
            moved_data = json.load(f).get('moved_data', [])

    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'version': 1,
                   'note': 'Generated by gamepro-app/tools/scripts_repo/make_retired.py - '
                           'old paths of moved/renamed scripts; Get Scripts removes unedited '
                           'local copies.',
                   'retired': retired, 'moved_data': moved_data}, f, indent=1)
        f.write('\n')
    print(f'{len(retired)} retired paths, {len(moved_data)} moved_data -> {out}')


if __name__ == '__main__':
    main()
